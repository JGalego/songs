#!/usr/bin/env python3
"""
The bright notes of the piano roll: one note per sung word, timed by src/karaoke.ts, pitched from the vocal.

  uv run --with librosa python scripts/melody.py      # -> src/melody.ts

pyin on the harmonic part of the full mix only hears the voice now and then, so the detections are merged across
repeated lines (every chorus sings the same tune), folded into one octave band, snapped to D minor (the song is
"something sad in D"), and the gaps are filled by interpolating between neighbours. It's a drawing of the melody,
not a transcription.
"""
import json, re
from pathlib import Path
import numpy as np
import librosa

ROOT = Path(__file__).resolve().parent.parent
y, sr = librosa.load(ROOT / "ghost_notes.mp3", sr=22050, mono=True)
f0, _, prob = librosa.pyin(librosa.effects.harmonic(y, margin=3.0), fmin=150, fmax=900, sr=sr, frame_length=2048, hop_length=256)
times = librosa.times_like(f0, sr=sr, hop_length=256)

src = (ROOT / "src/karaoke.ts").read_text()
word_times = json.loads(re.sub(r",\s*\]", "]", src[src.index("= [") + 2: src.rindex(";")]))
tl = (ROOT / "src/timeline.ts").read_text()
texts = [eval(s) for s in re.findall(r"L\([\d.]+, [\d.]+, ('(?:[^'\\]|\\.)*'|\"(?:[^\"\\]|\\.)*\")", tl)]
assert len(texts) == len(word_times)

LO, HI = 57, 74  # A3..D5
SCALE = [0, 2, 3, 5, 7, 8, 10]  # pitch classes relative to D: D E F G A Bb C


def snap(m):
    while m < LO: m += 12
    while m > HI: m -= 12
    rel = (round(m) - 2) % 12
    best = min(SCALE, key=lambda s: min(abs(s - rel), 12 - abs(s - rel)))
    return round(m) + ((best - rel + 6) % 12 - 6)


def detect(s, e):
    m = (times >= s) & (times < e) & (prob > 0.1) & ~np.isnan(f0)
    return float(librosa.hz_to_midi(np.median(f0[m]))) if m.sum() >= 2 else None


# raw detections per word, merged across lines with the same words
raw = [[detect(s, e) for s, e in wt] for wt in word_times]
merged = {}
for text, r in zip(texts, raw):
    merged.setdefault(text, []).append(r)
pitches, prev_mean = [], 64
for text, wt in zip(texts, word_times):
    cols = list(zip(*merged[text]))
    p = [snap(float(np.median([x for x in c if x is not None]))) if any(x is not None for x in c) else None for c in cols]
    known = [i for i, x in enumerate(p) if x is not None]
    if not known:
        p = [snap(prev_mean + (2 if i % 3 == 1 else 0) - (2 if i % 4 == 3 else 0)) for i in range(len(p))]
    else:
        for i in range(len(p)):
            if p[i] is None:
                a = max([k for k in known if k < i], default=None)
                b = min([k for k in known if k > i], default=None)
                if a is None: p[i] = p[b]
                elif b is None: p[i] = p[a]
                else: p[i] = snap(p[a] + (p[b] - p[a]) * (i - a) / (b - a) + (1 if (i * 7) % 3 == 0 else -1))
    prev_mean = float(np.mean(p))
    pitches.append(p)

with (ROOT / "src/melody.ts").open("w") as f:
    f.write("// Generated by scripts/melody.py: the sung melody, one [start, end, midi] per word of each LYRICS line.\n")
    f.write("export const MELODY: [number, number, number][][] = [\n")
    for wt, p in zip(word_times, pitches):
        f.write("  [" + ", ".join(f"[{s}, {e}, {m}]" for (s, e), m in zip(wt, p)) + "],\n")
    f.write("];\n")
for text, p in zip(texts, pitches):
    print(" ".join(f"{librosa.midi_to_note(m, unicode=False)}" for m in p), "|", text)
