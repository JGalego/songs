import * as THREE from 'three';

export const MONO = '"JetBrains Mono", ui-monospace, Menlo, Consolas, monospace';
export const SANS = '"Inter", system-ui, sans-serif';
/** The 2004 screens: a chunky bitmap-style face. */
export const PIXEL = '"VT323", "JetBrains Mono", monospace';

export async function loadFonts() {
  await Promise.all([
    document.fonts.load(`400 32px ${MONO}`),
    document.fonts.load(`700 32px ${MONO}`),
    document.fonts.load(`400 32px ${SANS}`),
    document.fonts.load(`600 32px ${SANS}`),
    document.fonts.load(`800 32px ${SANS}`),
    document.fonts.load(`400 32px ${PIXEL}`),
  ]);
}

/** Canvas pixels per logical pixel; logical units are 1080p. Set once at startup from the render height. */
let TEXT_SCALE = 1;
export const setTextScale = (s: number) => { TEXT_SCALE = s; };

/** A 2D canvas bound to a three.js texture. Redraws only when the key changes. */
export class CanvasTex {
  readonly canvas = document.createElement('canvas');
  readonly ctx: CanvasRenderingContext2D;
  readonly texture: THREE.CanvasTexture;
  private key = '';

  private readonly lw: number;
  private readonly lh: number;
  private readonly scale = TEXT_SCALE;

  /** w/h are logical (1080p) pixels; the backing canvas is scaled up for sharp text at higher resolutions. */
  constructor(w: number, h: number, nearest = false) {
    this.lw = w;
    this.lh = h;
    this.canvas.width = Math.ceil(w * this.scale);
    this.canvas.height = Math.ceil(h * this.scale);
    this.ctx = this.canvas.getContext('2d')!;
    this.texture = new THREE.CanvasTexture(this.canvas);
    this.texture.colorSpace = THREE.SRGBColorSpace;
    this.texture.anisotropy = 8;
    if (nearest) {
      this.texture.magFilter = THREE.NearestFilter;
      this.texture.minFilter = THREE.NearestFilter;
      this.texture.generateMipmaps = false;
    }
  }

  get w() { return this.lw; }
  get h() { return this.lh; }

  /** Calls `draw` (on a cleared canvas) only if `key` differs from the last draw. */
  draw(key: string, draw: (ctx: CanvasRenderingContext2D) => void) {
    if (key === this.key) return;
    this.key = key;
    this.ctx.setTransform(this.scale, 0, 0, this.scale, 0, 0);
    this.ctx.clearRect(0, 0, this.w, this.h);
    draw(this.ctx);
    this.texture.needsUpdate = true;
  }
}

export function wrap(ctx: CanvasRenderingContext2D, text: string, maxWidth: number): string[] {
  const words = text.split(' ');
  const lines: string[] = [];
  let line = '';
  for (const w of words) {
    const next = line ? `${line} ${w}` : w;
    if (ctx.measureText(next).width > maxWidth && line) {
      lines.push(line);
      line = w;
    } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}

export function roundRect(ctx: CanvasRenderingContext2D, x: number, y: number, w: number, h: number, r: number) {
  ctx.beginPath();
  ctx.roundRect(x, y, w, h, r);
}

/** Text revealed character by character over [t0, t0 + dur]. */
export function typed(text: string, t: number, t0: number, dur: number): string {
  if (t < t0) return '';
  const n = Math.floor(((t - t0) / Math.max(dur, 1e-3)) * text.length);
  return text.slice(0, Math.min(text.length, n));
}

/** Blinking block cursor. */
export const cursor = (t: number, rate = 1.6) => (Math.floor(t * rate * 2) % 2 === 0 ? '▍' : ' ');

// ── karaoke subtitles (word times come from src/karaoke.ts, generated by tools/karaoke.py)
type WordTimes = [number, number][];

/**
 * When each line is on screen. A line shows (dim) 0.35 s before its first word, but never while the previous line
 * is still being sung, and leaves 0.6 s after its last word or as soon as the next line shows. Back-to-back lines
 * swap instantly; lines with a gap around them fade.
 */
export function karaokeLines(times: WordTimes[]) {
  const shows = times.map((w, i) => {
    const first = w[0][0], prevLast = i ? times[i - 1][times[i - 1].length - 1][1] : -Infinity;
    return Math.min(first, Math.max(first - 0.35, prevLast));
  });
  const hides = times.map((w, i) => Math.min(w[w.length - 1][1] + 0.6, shows[i + 1] ?? Infinity));
  return times.map((_, i) => ({
    show: shows[i], hide: hides[i], fadeIn: i === 0 || hides[i - 1] < shows[i], fadeOut: hides[i] < (shows[i + 1] ?? Infinity),
  }));
}

/** The line on screen at t (index into LYRICS, or -1) and its opacity. */
export function karaokeAt(lines: ReturnType<typeof karaokeLines>, t: number) {
  const i = lines.findIndex((k) => t >= k.show && t < k.hide);
  if (i < 0) return { i, alpha: 0 };
  const k = lines[i];
  const alpha = (k.fadeIn ? smoothstep01((t - k.show) / 0.15) : 1) * (k.fadeOut ? 1 - smoothstep01((t - (k.hide - 0.4)) / 0.4) : 1);
  return { i, alpha };
}

/**
 * Draws `text` centered on (cx, y) with the current font: dim everywhere, and `fill` over the part already sung,
 * sweeping through each word while it's being sung. Words are the space-separated words of the line, matching
 * `times` one to one. Shrinks the font to fit `maxW` if needed.
 */
export function karaokeText(ctx: CanvasRenderingContext2D, text: string, times: WordTimes, t: number, cx: number, y: number, maxW: number, dim: string, fill: string) {
  const w0 = ctx.measureText(text).width;
  if (w0 > maxW) ctx.font = ctx.font.replace(/(\d+(?:\.\d+)?)px/, (_, px) => `${Math.floor((parseFloat(px) * maxW) / w0)}px`);
  const width = ctx.measureText(text).width, x0 = cx - width / 2;
  const words = text.split(' ');
  let edge = x0;
  for (let w = 0; w < words.length && w < times.length; w++) {
    const [s, e] = times[w];
    if (t < s) break;
    const before = ctx.measureText(words.slice(0, w).join(' ') + (w ? ' ' : '')).width;
    edge = x0 + before + ctx.measureText(words[w]).width * Math.min(1, Math.max(0, (t - s) / Math.max(0.05, e - s)));
  }
  ctx.textAlign = 'left';
  ctx.textBaseline = 'middle';
  ctx.fillStyle = dim;
  ctx.fillText(text, x0, y);
  ctx.save();
  ctx.beginPath();
  ctx.rect(-1e5, -1e5, edge + 1e5, 2e5); // everything left of the edge (in drawing units, not canvas pixels)
  ctx.clip();
  ctx.fillStyle = fill;
  ctx.fillText(text, x0, y);
  ctx.restore();
}

const smoothstep01 = (x: number) => { const u = Math.min(1, Math.max(0, x)); return u * u * (3 - 2 * u); };
